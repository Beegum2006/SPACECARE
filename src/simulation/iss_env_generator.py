"""
SPACECARE Simulation Engine - ISS Environmental Telemetry (ECLSS)
Simulates International Space Station cabin atmosphere and life support parameters.

DISCLAIMER: All environmental data generated by this module is SYNTHETIC
for systems engineering demonstration and life support analysis.
"""

import numpy as np
from datetime import datetime, timedelta, timezone
from typing import Dict, Any, List, Optional


ENV_ANOMALY_MODES = [
    "NOMINAL",
    "CDRA_SCRUBBER_MALFUNCTION",
    "CABIN_DEPRESSURIZATION",
    "THERMAL_LOOP_DEGRADATION",
    "O2_GENERATION_FAULT"
]

ISS_MODULES = [
    "Destiny Laboratory (US Lab)",
    "Columbus Orbital Facility (ESA)",
    "Kibo Module (JAXA)",
    "Harmony (Node 2)",
    "Tranquility (Node 3 ECLSS Hub)"
]


def generate_env_snapshot(
    module_name: str = "Destiny Laboratory (US Lab)",
    timestamp: Optional[datetime] = None,
    anomaly_mode: str = "NOMINAL"
) -> Dict[str, Any]:
    """
    Generates a single point-in-time ISS ECLSS environmental telemetry snapshot.
    """
    if timestamp is None:
        timestamp = datetime.now(timezone.utc)

    # Nominal baselines for ISS ECLSS
    b_press = 14.70  # psi (Earth atmospheric sea-level pressure)
    b_co2 = 2.80     # mmHg (ISS CDRA maintains below 3.5 mmHg)
    b_o2 = 21.05     # % (Atmospheric O2 target)
    b_temp = 22.20   # °C (Comfort thermal range)
    b_hum = 46.50    # % (Relative humidity target)
    b_rad = 22.50    # µSv/h (Orbital background dosimeter baseline)

    # Small environmental sensor flutter
    press = b_press + np.random.normal(0, 0.03)
    co2 = b_co2 + np.random.normal(0, 0.08)
    o2 = b_o2 + np.random.normal(0, 0.05)
    temp = b_temp + np.random.normal(0, 0.12)
    hum = b_hum + np.random.normal(0, 0.6)
    rad = b_rad + np.random.normal(0, 0.8)
    status = "NOMINAL"

    # Apply Anomaly Scenarios
    if anomaly_mode == "CDRA_SCRUBBER_MALFUNCTION":
        # Carbon Dioxide Removal Assembly failure: CO2 climbs > 4.5 mmHg (causes lethargy, headaches)
        co2 = b_co2 + np.random.uniform(2.2, 3.8)
        status = "ECLSS_WARNING"

    elif anomaly_mode == "CABIN_DEPRESSURIZATION":
        # Slow hull seal degradation or micrometeoroid penetration
        press = b_press - np.random.uniform(1.8, 3.2)
        o2 = b_o2 - np.random.uniform(1.0, 2.2)
        status = "DECOMPRESSION_CRITICAL"

    elif anomaly_mode == "THERMAL_LOOP_DEGRADATION":
        # Internal Active Thermal Control System (IATCS) loop degraded
        temp = b_temp + np.random.uniform(5.5, 8.5)
        hum = b_hum + np.random.uniform(20.0, 30.0)
        status = "THERMAL_WARNING"

    elif anomaly_mode == "O2_GENERATION_FAULT":
        # Oxygen Generation System (OGS) failure
        o2 = b_o2 - np.random.uniform(2.5, 4.5)
        status = "HYPOXIC_ENVIRONMENT_WARNING"

    # Physiological / environmental physical bounds
    press = float(np.clip(press, 8.0, 16.0))
    co2 = float(np.clip(co2, 0.5, 12.0))
    o2 = float(np.clip(o2, 14.0, 25.0))
    temp = float(np.clip(temp, 15.0, 38.0))
    hum = float(np.clip(hum, 15.0, 95.0))
    rad = float(np.clip(rad, 10.0, 150.0))

    return {
        "timestamp": timestamp.strftime("%Y-%m-%d %H:%M:%S"),
        "module_name": module_name,
        "cabin_pressure_psi": round(press, 2),
        "co2_partial_pressure_mmhg": round(co2, 2),
        "o2_percentage": round(o2, 2),
        "temperature_celsius": round(temp, 2),
        "relative_humidity_pct": round(hum, 1),
        "radiation_level_usv_h": round(rad, 2),
        "status": status,
        "is_simulated": 1
    }


def generate_env_series(
    module_name: str = "Destiny Laboratory (US Lab)",
    count: int = 30,
    interval_seconds: int = 15,
    anomaly_mode: str = "NOMINAL",
    anomaly_onset_index: Optional[int] = None
) -> List[Dict[str, Any]]:
    """Generates a historical time series of ISS environmental readings."""
    now = datetime.now(timezone.utc)
    series = []
    
    for i in range(count):
        t = now - timedelta(seconds=(count - 1 - i) * interval_seconds)
        mode = anomaly_mode
        if anomaly_onset_index is not None and i < anomaly_onset_index:
            mode = "NOMINAL"
            
        reading = generate_env_snapshot(module_name=module_name, timestamp=t, anomaly_mode=mode)
        series.append(reading)
        
    return series
