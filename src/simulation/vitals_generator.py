"""
SPACECARE Simulation Engine - Vitals Generator
Generates physiologically realistic astronaut vital signs with circadian drift,
individual baseline variance, and spaceflight anomaly induction.

DISCLAIMER: All data generated by this module is purely SYNTHETIC for systems
engineering and demonstration. It is not real flight telemetry.
"""

import numpy as np
from datetime import datetime, timedelta, timezone
from typing import Dict, Any, List, Tuple, Optional


ANOMALY_MODES = [
    "NOMINAL",
    "HYPOXIA",
    "TACHYCARDIA_ARRHYTHMIA",
    "HEAT_STRESS",
    "EVA_EXERTION"
]


def generate_vitals_snapshot(
    astronaut: Dict[str, Any],
    timestamp: Optional[datetime] = None,
    anomaly_mode: str = "NOMINAL",
    step_index: int = 0
) -> Dict[str, Any]:
    """
    Generates a single point-in-time vital signs reading for an astronaut.
    
    Args:
        astronaut: Dictionary containing astronaut baseline metrics.
        timestamp: Timestamp of the reading (defaults to UTC now).
        anomaly_mode: One of ANOMALY_MODES.
        step_index: Used for circadian sinusoidal calculation.
    
    Returns:
        Dictionary of simulated vital signs.
    """
    if timestamp is None:
        timestamp = datetime.now(timezone.utc)

    # Base personal values from astronaut profile
    b_hr = float(astronaut.get("baseline_hr", 70.0))
    b_spo2 = float(astronaut.get("baseline_spo2", 98.0))
    b_sys = float(astronaut.get("baseline_bp_sys", 118.0))
    b_dia = float(astronaut.get("baseline_bp_dia", 76.0))
    b_temp = float(astronaut.get("baseline_temp", 36.8))
    b_rr = float(astronaut.get("baseline_rr", 14.0))
    b_hrv = float(astronaut.get("baseline_hrv", 55.0))

    # Natural circadian oscillation (24-hour sinusoidal wave simulation)
    hour = timestamp.hour + timestamp.minute / 60.0
    circadian_wave = np.sin((hour - 6.0) * (2 * np.pi / 24.0))

    # Small random walk noise
    noise_hr = np.random.normal(0, 1.2) + (circadian_wave * 2.5)
    noise_spo2 = np.random.normal(0, 0.2)
    noise_sys = np.random.normal(0, 1.5) + (circadian_wave * 2.0)
    noise_dia = np.random.normal(0, 1.0) + (circadian_wave * 1.5)
    noise_temp = np.random.normal(0, 0.04) + (circadian_wave * 0.15)
    noise_rr = np.random.normal(0, 0.4)
    noise_hrv = np.random.normal(0, 2.0) - (circadian_wave * 3.0)

    hr = b_hr + noise_hr
    spo2 = b_spo2 + noise_spo2
    sys_bp = b_sys + noise_sys
    dia_bp = b_dia + noise_dia
    temp = b_temp + noise_temp
    rr = b_rr + noise_rr
    hrv = b_hrv + noise_hrv
    ecg_status = "NORMAL_SINUS"
    anomaly_flag = 0
    anomaly_score = 0.05  # baseline nominal anomaly score

    # Apply Anomaly Modes
    if anomaly_mode == "HYPOXIA":
        # Oxygen starvation: rapid SpO2 drop, elevated RR and compensatory tachycardia
        spo2 = np.clip(b_spo2 - np.random.uniform(9.0, 15.0), 78.0, 89.0)
        rr = b_rr + np.random.uniform(8.0, 14.0)
        hr = b_hr + np.random.uniform(25.0, 45.0)
        hrv = max(18.0, b_hrv - 28.0)
        ecg_status = "SINUS_TACHYCARDIA"
        anomaly_flag = 1
        anomaly_score = -0.42

    elif anomaly_mode == "TACHYCARDIA_ARRHYTHMIA":
        # Acute cardiac arrhythmia: severe HR spike, collapsed HRV, elevated systolic
        hr = b_hr + np.random.uniform(55.0, 85.0)
        hrv = np.random.uniform(12.0, 22.0)
        sys_bp = b_sys + np.random.uniform(25.0, 40.0)
        dia_bp = b_dia + np.random.uniform(10.0, 18.0)
        ecg_status = "PAROXYSMAL_TACHYCARDIA"
        anomaly_flag = 1
        anomaly_score = -0.65

    elif anomaly_mode == "HEAT_STRESS":
        # Thermal regulation failure: core temp rises > 38.5 C, HR climbs
        temp = np.random.uniform(38.6, 39.8)
        hr = b_hr + np.random.uniform(20.0, 38.0)
        rr = b_rr + np.random.uniform(4.0, 8.0)
        ecg_status = "SINUS_TACHYCARDIA"
        anomaly_flag = 1
        anomaly_score = -0.38

    elif anomaly_mode == "EVA_EXERTION":
        # Heavy physical workload during extravehicular activity (spacewalk)
        hr = b_hr + np.random.uniform(35.0, 55.0)
        rr = b_rr + np.random.uniform(6.0, 10.0)
        sys_bp = b_sys + np.random.uniform(16.0, 26.0)
        temp = b_temp + np.random.uniform(0.5, 0.9)
        ecg_status = "PHYSIOLOGICAL_TACHYCARDIA"
        anomaly_flag = 0  # Expected operational exertion, not an uncontrolled anomaly
        anomaly_score = 0.01

    # Physiological hard boundary safeguards
    hr = float(np.clip(hr, 40.0, 200.0))
    spo2 = float(np.clip(spo2, 70.0, 100.0))
    sys_bp = float(np.clip(sys_bp, 80.0, 210.0))
    dia_bp = float(np.clip(dia_bp, 50.0, 130.0))
    temp = float(np.clip(temp, 35.0, 42.0))
    rr = float(np.clip(rr, 6.0, 35.0))
    hrv = float(np.clip(hrv, 8.0, 120.0))

    return {
        "astronaut_id": astronaut["id"],
        "timestamp": timestamp.strftime("%Y-%m-%d %H:%M:%S"),
        "heart_rate": round(hr, 1),
        "blood_pressure_sys": round(sys_bp, 1),
        "blood_pressure_dia": round(dia_bp, 1),
        "spo2": round(spo2, 1),
        "core_temperature": round(temp, 2),
        "respiration_rate": round(rr, 1),
        "hrv_rmssd": round(hrv, 1),
        "ecg_status": ecg_status,
        "is_simulated": 1,
        "anomaly_score": round(anomaly_score, 3),
        "anomaly_flag": anomaly_flag
    }


def generate_vitals_series(
    astronaut: Dict[str, Any],
    count: int = 30,
    interval_seconds: int = 10,
    anomaly_mode: str = "NOMINAL",
    anomaly_onset_index: Optional[int] = None
) -> List[Dict[str, Any]]:
    """
    Generates a historical time series of vital sign readings.
    If anomaly_onset_index is specified, transitions from NOMINAL to anomaly_mode at that point.
    """
    now = datetime.now(timezone.utc)
    series = []
    
    for i in range(count):
        t = now - timedelta(seconds=(count - 1 - i) * interval_seconds)
        mode = anomaly_mode
        if anomaly_onset_index is not None and i < anomaly_onset_index:
            mode = "NOMINAL"
            
        reading = generate_vitals_snapshot(astronaut, timestamp=t, anomaly_mode=mode, step_index=i)
        series.append(reading)
        
    return series


def generate_synthetic_ecg_trace(
    heart_rate_bpm: float = 72.0,
    duration_sec: float = 3.0,
    sampling_rate: int = 100,
    rhythm: str = "NORMAL_SINUS"
) -> Tuple[np.ndarray, np.ndarray]:
    """
    Generates a synthetic P-Q-R-S-T electrocardiogram waveform for interactive visualization.
    Returns:
        (time_array_sec, voltage_array_mv)
    """
    total_samples = int(duration_sec * sampling_rate)
    t = np.linspace(0, duration_sec, total_samples)
    voltage = np.zeros(total_samples)

    # RR interval in seconds
    rr_interval = 60.0 / max(30.0, heart_rate_bpm)
    
    # Heartbeat peak times
    beat_times = []
    current_beat = 0.15
    while current_beat < duration_sec:
        # Small physiological jitter
        jitter = np.random.normal(0, 0.015) if rhythm == "NORMAL_SINUS" else np.random.normal(0, 0.06)
        beat_times.append(current_beat)
        current_beat += rr_interval + jitter

    for bt in beat_times:
        # P wave (atrial depolarization): small smooth hump before QRS
        p_center = bt - 0.16
        voltage += 0.15 * np.exp(-((t - p_center) ** 2) / (2 * (0.025 ** 2)))

        # Q wave: small downward deflection
        q_center = bt - 0.04
        voltage -= 0.18 * np.exp(-((t - q_center) ** 2) / (2 * (0.012 ** 2)))

        # R wave: sharp, high positive spike (ventricular depolarization)
        r_height = 1.2 if rhythm != "PAROXYSMAL_TACHYCARDIA" else 1.45
        voltage += r_height * np.exp(-((t - bt) ** 2) / (2 * (0.015 ** 2)))

        # S wave: downward deflection right after R
        s_center = bt + 0.04
        voltage -= 0.35 * np.exp(-((t - s_center) ** 2) / (2 * (0.014 ** 2)))

        # T wave: broader positive hump (ventricular repolarization)
        t_center = bt + 0.22
        voltage += 0.32 * np.exp(-((t - t_center) ** 2) / (2 * (0.045 ** 2)))

    # Baseline physiological wander and high-frequency sensor noise
    noise = np.random.normal(0, 0.02, total_samples)
    wander = 0.05 * np.sin(2 * np.pi * 0.3 * t)
    voltage = voltage + noise + wander

    return t, voltage
